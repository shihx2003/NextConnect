package proxy

import (
	"fmt"
	"net"
	"net/netip"
	"strings"

	"github.com/nextconnect/core/pkg/model"
)

// GeneratePAC 根据当前分流模式与规则列表生成标准 PAC（Proxy Auto-Config）脚本。
func GeneratePAC(httpPort int, socksPort int, mode model.RoutingMode, rules []model.RuleEntry) string {
	if httpPort <= 0 {
		httpPort = 10809
	}
	if socksPort <= 0 {
		socksPort = 10808
	}
	proxyExpr := fmt.Sprintf("PROXY 127.0.0.1:%d; SOCKS5 127.0.0.1:%d; DIRECT", httpPort, socksPort)

	var bypassDomains []string
	var tunnelDomains []string
	var tunnelCIDRs []string

	for _, r := range rules {
		switch r.Type {
		case "DOMAIN", "DOMAIN-WILDCARD":
			if r.Action == model.RuleActionDirect {
				bypassDomains = append(bypassDomains, r.Pattern)
			} else {
				tunnelDomains = append(tunnelDomains, r.Pattern)
			}
		case "IP-CIDR":
			if r.Action == model.RuleActionTunnel {
				if pfx, err := netip.ParsePrefix(r.Pattern); err == nil && pfx.Addr().Is4() {
					ip := pfx.Addr().String()
					mask := net.IP(net.CIDRMask(pfx.Bits(), 32)).String()
					tunnelCIDRs = append(tunnelCIDRs, fmt.Sprintf("isInNet(host, %q, %q)", ip, mask))
				}
			}
		}
	}

	var b strings.Builder
	b.WriteString("// Generated by NextConnect Core\n")
	b.WriteString("function FindProxyForURL(url, host) {\n")
	b.WriteString("  var h = host.toLowerCase();\n")
	b.WriteString("  if (isPlainHostName(h) || h === \"localhost\" || isInNet(h, \"127.0.0.0\", \"255.0.0.0\")) {\n")
	b.WriteString("    return \"DIRECT\";\n")
	b.WriteString("  }\n")

	for _, bd := range bypassDomains {
		fmt.Fprintf(&b, "  if (h === %q || shExpMatch(h, %q)) { return \"DIRECT\"; }\n", bd, "*."+bd)
	}

	if mode == model.RoutingModeGlobal {
		fmt.Fprintf(&b, "  return %q;\n", proxyExpr)
		b.WriteString("}\n")
		return b.String()
	}

	for _, td := range tunnelDomains {
		if strings.HasPrefix(td, "*.") && strings.Count(td, "*") == 1 {
			bare := td[2:]
			fmt.Fprintf(&b, "  if (h === %q || shExpMatch(h, %q)) { return %q; }\n", bare, td, proxyExpr)
		} else if strings.Contains(td, "*") {
			fmt.Fprintf(&b, "  if (shExpMatch(h, %q)) { return %q; }\n", td, proxyExpr)
		} else {
			fmt.Fprintf(&b, "  if (h === %q) { return %q; }\n", td, proxyExpr)
		}
	}

	for _, cidrCond := range tunnelCIDRs {
		fmt.Fprintf(&b, "  if (%s) { return %q; }\n", cidrCond, proxyExpr)
	}

	b.WriteString("  return \"DIRECT\";\n")
	b.WriteString("}\n")
	return b.String()
}
